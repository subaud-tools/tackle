const operatorsFixture = `package fixture

import "fmt"

const greeting = "hi"

func F(a, b int, ok, done bool) {
	if a == b {
		return
	}
	if a != b {
		return
	}
	if a < b {
		return
	}
	if a > b {
		return
	}
	if a <= b {
		return
	}
	if a >= b {
		return
	}
	if ok && !done {
		return
	}
	if ok || !done {
		return
	}
	sum := a + b
	diff := a - b
	prod := a * b
	if !ok {
		fmt.Println(sum, diff, prod)
		return
	}
	if true {
		return
	}
	if false {
		return
	}
	n := 41
	var f float64 = 3.5
	fmt.Println(greeting, n, f)
}
`

var descSuffix = regexp.MustCompile(`^line \d+: (.+)$`)

func TestGoSitesOperators(t *testing.T) {
	m := For("go")
	if m == nil {
		t.Fatal(`For("go") = nil`)
	}
	sites, err := m.Sites("", "fixture.go", []byte(operatorsFixture))
	if err != nil {
		t.Fatalf("Sites: %v", err)
	}

	want := map[string]int{
		"flip ==":       1,
		"flip !=":       1,
		"flip <":        1,
		"flip >":        1,
		"flip <=":       1,
		"flip >=":       1,
		"flip &&":       1,
		"flip ||":       1,
		"drop !":        3,
		"flip +":        1,
		"flip -":        1,
		"flip *":        1,
		"flip true":     1,
		"flip false":    1,
		"+1 int":        1,
		"+1 float":      1,
		"mutate string": 1,
	}
	got := map[string]int{}
	for _, s := range sites {
		sub := descSuffix.FindStringSubmatch(s.Desc)
		if sub == nil {
			t.Errorf("Desc %q does not match expected format", s.Desc)
			continue
		}
		got[sub[1]]++
	}
	if len(sites) != 19 {
		t.Errorf("len(sites) = %d, want 19; got desc counts %+v", len(sites), got)
	}
	for k, wantN := range want {
		if got[k] != wantN {
			t.Errorf("desc %q: got %d, want %d", k, got[k], wantN)
		}
	}

	// Every single-site mutation of the fixture must still parse and
	// type-check: vet each mutated variant in its own temp module.
	src := []byte(operatorsFixture)
	for _, s := range sites {
		mutated, err := Apply(src, s)
		if err != nil {
			t.Fatalf("Apply(%+v): %v", s, err)
		}
		vetGoFixture(t, mutated, s.Desc)
	}
}

func TestGoSitesSkipImportsTagsGenerated(t *testing.T) {
	m := For("go")

	const withTagsAndImports = `package fixture

import (
	"fmt"
	"strings"
)

type T struct {
	Name string ` + "`json:\"true\"`" + `
	OK   bool   ` + "`json:\"is_ok\"`" + `
}

func Use() {
	fmt.Println(strings.ToUpper("x"))
}
`
	sites, err := m.Sites("", "fixture.go", []byte(withTagsAndImports))
	if err != nil {
		t.Fatalf("Sites: %v", err)
	}
	for _, s := range sites {
		repl := string([]byte(withTagsAndImports)[s.Start:s.End])
		if repl == `"fmt"` || repl == `"strings"` {
			t.Errorf("mutated an import path: %+v", s)
		}
		if repl == "`json:\"true\"`" || repl == "`json:\"is_ok\"`" {
			t.Errorf("mutated a struct tag: %+v", s)
		}
	}

	const generated = `// Code generated by cull; DO NOT EDIT.

package fixture

func F(a, b int) bool {
	return a == b
}
`
	genSites, err := m.Sites("", "fixture_gen.go", []byte(generated))
	if err != nil {
		t.Fatalf("Sites (generated): %v", err)
	}
	if len(genSites) != 0 {
		t.Errorf("generated file: got %d sites, want 0: %+v", len(genSites), genSites)
	}

	testSites, err := m.Sites("", "fixture_test.go", []byte(operatorsFixture))
	if err != nil {
		t.Fatalf("Sites (_test.go): %v", err)
	}
	if len(testSites) != 0 {
		t.Errorf("_test.go file: got %d sites, want 0: %+v", len(testSites), testSites)
	}
}

func TestGoSitesUnicodeOffsets(t *testing.T) {
	const src = `package fixture

const greeting = "héllo wörld"

func F(a, b int) bool {
	return a == b
}
`
	m := For("go")
	sites, err := m.Sites("", "fixture.go", []byte(src))
	if err != nil {
		t.Fatalf("Sites: %v", err)
	}
	var eq *Site
	for i := range sites {
		if sites[i].Desc == "line 6: flip ==" {
			eq = &sites[i]
		}
	}
	if eq == nil {
		t.Fatalf("no comparison site found among %+v", sites)
	}
	out, err := Apply([]byte(src), *eq)
	if err != nil {
		t.Fatalf("Apply: %v", err)
	}
	want := `package fixture

const greeting = "héllo wörld"

func F(a, b int) bool {
	return a != b
}
`
	if string(out) != want {
		t.Fatalf("Apply with unicode-preceded offsets:\ngot:  %q\nwant: %q", out, want)
	}
}

// vetGoFixture writes src into a throwaway module and runs `go vet` on it,
// failing t if vet reports a problem. desc identifies the mutation under
// test in failure messages.
func vetGoFixture(t *testing.T, src []byte, desc string) {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module fixture\n\ngo 1.21\n"), 0o644); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "fixture.go"), src, 0o644); err != nil {
		t.Fatalf("write fixture.go: %v", err)
	}
	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go vet failed for mutation %q:\n%s\nsrc:\n%s", desc, out, src)
	}
}
